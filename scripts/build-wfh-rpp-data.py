#!/usr/bin/env python3
"""Generate js/wfh_calculator/wfh-rpp-data.js from BEA Regional Price Parities.

Run from the repo root:  python scripts/build-wfh-rpp-data.py

Two steps:
1. If the BEA download zips are in data/wfh_calculator/sources/ (local only),
   rewrite data/wfh_calculator/bea_rpp_2024.csv from them: every metro area,
   every state, the US and the US nonmetro portion, with the all-items and
   housing (rent) parities for the latest year.
2. Write the browser module from that committed CSV.

Values are copied as published, rounded to one decimal. Nothing is averaged
or adjusted for inflation: a comparison between two places uses their ratio,
which inflation does not change.
"""
import csv
import io
import json
import os
import zipfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(REPO, "data", "wfh_calculator")
SOURCES = os.path.join(DATA, "sources")
CSV_OUT = os.path.join(DATA, "bea_rpp_2024.csv")
JS_OUT = os.path.join(REPO, "js", "wfh_calculator", "wfh-rpp-data.js")
YEAR = "2024"
ZIPS = [
    ("bea_marpp_2008_2024.zip", "MARPP_MSA_2008_2024.csv"),
    ("bea_sarpp_2008_2024.zip", "SARPP_STATE_2008_2024.csv"),
]
LINES = {"1": "all_items", "3": "housing"}


def read_zip_rows():
    rows = {}
    for zip_name, member in ZIPS:
        with zipfile.ZipFile(os.path.join(SOURCES, zip_name)) as z:
            text = z.read(member).decode("latin-1")
        for r in csv.DictReader(io.StringIO(text)):
            fips = (r.get("GeoFIPS") or "").strip().strip('"').strip()
            line = (r.get("LineCode") or "").strip()
            if not fips.isdigit() or line not in LINES:
                continue
            name = r["GeoName"].strip()
            if fips == "00000":
                kind = "us"
            elif fips == "00999":
                kind, name = "us", "United States, outside metro areas"
            elif fips.endswith("000"):
                kind = "state"
            else:
                kind = "metro"
                # BEA writes one name without the parentheses.
                name = name.replace(" (Metropolitan Statistical Area)", "").replace(" Metropolitan Statistical Area", "")
            name = name.replace(" *", "")
            value = r[YEAR].strip()
            entry = rows.setdefault(fips, {"fips": fips, "name": name, "kind": kind})
            entry[LINES[line]] = "" if value in ("(NA)", "") else f"{float(value):.1f}"
    return sorted(rows.values(), key=lambda e: ({"us": 0, "state": 1, "metro": 2}[e["kind"]], e["name"]))


def write_csv(rows):
    with open(CSV_OUT, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["fips", "name", "kind", "all_items", "housing"], lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def write_js():
    with open(CSV_OUT, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    places = [[r["fips"], r["name"], r["kind"], float(r["all_items"]), float(r["housing"]) if r["housing"] else None]
              for r in rows if r["all_items"]]
    body = ",\n".join("    " + json.dumps(p, ensure_ascii=False) for p in places)
    js = (
        "// GENERATED by scripts/build-wfh-rpp-data.py from data/wfh_calculator/bea_rpp_2024.csv.\n"
        "// Do not edit by hand. BEA Regional Price Parities, US = 100.\n"
        "// Each row: [fips, name, kind (us, state, metro), all items, housing].\n\n"
        f"export const RPP_YEAR = {YEAR};\n"
        "export const RPP_RELEASED = 'February 19, 2026';\n"
        "export const RPP_URL = 'https://www.bea.gov/data/prices-inflation/regional-price-parities-state-and-metro-area';\n\n"
        f"export const RPP_PLACES = [\n{body},\n];\n"
    )
    with open(JS_OUT, "w", newline="\n", encoding="utf-8") as f:
        f.write(js)
    return len(places)


if __name__ == "__main__":
    if all(os.path.exists(os.path.join(SOURCES, z)) for z, _ in ZIPS):
        write_csv(read_zip_rows())
        print("rewrote", os.path.relpath(CSV_OUT, REPO))
    print("wrote", os.path.relpath(JS_OUT, REPO), write_js(), "places")
